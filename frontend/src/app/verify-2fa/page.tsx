'use client';

import { useState, useEffect } from 'react';
import { useRouter } from 'next/navigation';
import Link from 'next/link';
import {
  ShieldCheck,
  KeyRound,
  ArrowRight,
  AlertCircle,
  CheckCircle2,
  Lock,
  Smartphone,
  ArrowLeft,
  Sparkles,
} from 'lucide-react';
import { ROUTES } from '@/constants/routes';
import { STORAGE_KEYS } from '@/constants/ui-constants';

export default function Verify2FaPage() {
  const router = useRouter();
  const [email, setEmail] = useState('admin@bargorya.com');
  const [code, setCode] = useState('');
  const [isBackupMode, setIsBackupMode] = useState(false);
  const [rememberDevice, setRememberDevice] = useState(true);
  const [error, setError] = useState('');
  const [success, setSuccess] = useState(false);
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    try {
      const storedUser = localStorage.getItem(STORAGE_KEYS.USER_DATA);
      if (storedUser) {
        const parsed = JSON.parse(storedUser);
        if (parsed.email) setEmail(parsed.email);
      }
    } catch {
      // ignore
    }
  }, []);

  const handleVerify = (e: React.FormEvent) => {
    e.preventDefault();
    setError('');

    if (!isBackupMode) {
      if (code.trim().length !== 6) {
        setError('Please enter a 6-digit verification code.');
        return;
      }
    } else {
      if (code.trim().length < 8) {
        setError('Please enter a valid backup recovery code (e.g. 8A41-92F0).');
        return;
      }
    }

    setLoading(true);

    setTimeout(() => {
      setLoading(false);
      setSuccess(true);
      // Persist auth token
      localStorage.setItem(STORAGE_KEYS.ACCESS_TOKEN, 'mock_jwt_token_2fa_verified_2026');
      localStorage.setItem('admin:2fa:lastVerified', new Date().toISOString());

      setTimeout(() => {
        router.push(ROUTES.ADMIN.DASHBOARD);
      }, 1000);
    }, 700);
  };

  const handleAutoFillDemo = () => {
    if (isBackupMode) {
      setCode('8A41-92F0');
    } else {
      setCode('884219');
    }
    setError('');
  };

  return (
    <div className="min-h-screen bg-slate-950 flex flex-col justify-center py-12 sm:px-6 lg:px-8 relative overflow-hidden">
      
      {/* Background Ambient Glow */}
      <div className="absolute top-1/4 left-1/2 -translate-x-1/2 -translate-y-1/2 w-96 h-96 bg-indigo-600/20 rounded-full blur-3xl pointer-events-none" />

      <div className="sm:mx-auto sm:w-full sm:max-w-md relative z-10 px-4">
        
        {/* Card */}
        <div className="bg-white rounded-3xl p-6 sm:p-8 shadow-2xl border border-slate-800/10 space-y-6">
          
          {/* Header */}
          <div className="text-center space-y-2">
            <div className="w-12 h-12 rounded-2xl bg-indigo-50 border border-indigo-100 text-indigo-600 flex items-center justify-center mx-auto shadow-xs">
              {isBackupMode ? <KeyRound size={24} /> : <Smartphone size={24} />}
            </div>
            
            <h1 className="text-xl sm:text-2xl font-black text-slate-900 tracking-tight">
              {isBackupMode ? 'Enter Recovery Backup Code' : 'Two-Factor Authentication'}
            </h1>
            
            <p className="text-xs text-slate-500 max-w-xs mx-auto">
              {isBackupMode
                ? 'Enter one of your 8-character single-use emergency backup recovery codes.'
                : 'A 6-digit security code was generated by your authenticator app.'}
            </p>

            <div className="pt-1 inline-flex items-center gap-1 px-3 py-1 bg-slate-100 rounded-full text-xs font-semibold text-slate-700">
              <span className="w-2 h-2 rounded-full bg-emerald-500 animate-pulse" />
              <span>{email}</span>
            </div>
          </div>

          {/* Feedback Alerts */}
          {error && (
            <div className="p-3 bg-rose-50 border border-rose-200 rounded-xl text-rose-700 text-xs flex items-center gap-2">
              <AlertCircle size={16} className="shrink-0" />
              <span>{error}</span>
            </div>
          )}

          {success && (
            <div className="p-3 bg-emerald-50 border border-emerald-200 rounded-xl text-emerald-800 text-xs flex items-center gap-2">
              <CheckCircle2 size={16} className="shrink-0 text-emerald-600" />
              <span className="font-bold">Authentication verified! Redirecting to dashboard...</span>
            </div>
          )}

          {/* Verification Form */}
          <form onSubmit={handleVerify} className="space-y-4">
            <div className="space-y-1.5">
              <label className="text-xs font-bold text-slate-700 block">
                {isBackupMode ? 'Backup Recovery Code' : '6-Digit TOTP Passcode'}
              </label>
              
              <div className="relative">
                <input
                  type="text"
                  required
                  autoFocus
                  maxLength={isBackupMode ? 10 : 6}
                  value={code}
                  onChange={(e) => {
                    if (isBackupMode) {
                      setCode(e.target.value.toUpperCase());
                    } else {
                      setCode(e.target.value.replace(/\D/g, ''));
                    }
                  }}
                  placeholder={isBackupMode ? '8A41-92F0' : '••••••'}
                  className="w-full text-center font-mono text-2xl tracking-[0.3em] font-black bg-slate-50 border border-slate-200 rounded-2xl py-3 focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 uppercase placeholder:text-slate-300"
                />
              </div>
            </div>

            {/* Remember Device Checkbox */}
            <div className="flex items-center justify-between text-xs">
              <label className="flex items-center gap-2 cursor-pointer text-slate-600 font-medium select-none">
                <input
                  type="checkbox"
                  checked={rememberDevice}
                  onChange={(e) => setRememberDevice(e.target.checked)}
                  className="rounded border-slate-300 text-indigo-600 focus:ring-indigo-500"
                />
                <span>Trust this browser for 30 days</span>
              </label>

              <button
                type="button"
                onClick={handleAutoFillDemo}
                className="text-indigo-600 hover:text-indigo-700 font-bold flex items-center gap-1 cursor-pointer"
              >
                <Sparkles size={13} /> Demo Fill
              </button>
            </div>

            {/* Submit Button */}
            <button
              type="submit"
              disabled={loading || success}
              className="w-full py-3 bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs sm:text-sm rounded-xl shadow-xs transition flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
            >
              {loading ? 'Verifying Credentials...' : 'Verify & Enter ProCMS'}
              <ArrowRight size={16} />
            </button>
          </form>

          {/* Toggle Modes */}
          <div className="pt-2 border-t border-slate-100 flex flex-col items-center gap-2 text-xs">
            <button
              type="button"
              onClick={() => {
                setIsBackupMode(!isBackupMode);
                setCode('');
                setError('');
              }}
              className="text-slate-600 hover:text-slate-900 font-bold transition cursor-pointer"
            >
              {isBackupMode
                ? '← Use 6-Digit Authenticator App instead'
                : 'Lost phone? Use a Backup Recovery Code'}
            </button>

            <Link
              href={ROUTES.AUTH.LOGIN}
              className="text-slate-400 hover:text-slate-600 flex items-center gap-1 text-[11px] font-medium"
            >
              <ArrowLeft size={12} /> Return to standard login
            </Link>
          </div>

        </div>

        {/* Security Footer Notice */}
        <div className="mt-6 text-center text-xs text-slate-400 flex items-center justify-center gap-2">
          <ShieldCheck size={14} className="text-emerald-400" />
          <span>Encrypted with 256-bit AES &amp; RFC 6238 Standard</span>
        </div>

      </div>
    </div>
  );
}
